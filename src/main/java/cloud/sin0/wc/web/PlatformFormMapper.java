package cloud.sin0.wc.web;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Turns a form of the platform itself (a {@code Resource} of any module, e.g. {@code directorio/empresa}) into the
 * builder/fill model {@code {meta, fields}}, so the site can render it for data capture or open it in the builder as a
 * starting point. Platform component types are richer than the builder's (dynamic lists such as {@code regimen} or
 * {@code modulos}); anything that is not a simple input becomes a text input, and a list whose values are inline
 * ({@code origin} = inlinevalues) becomes a select. Input is hostile-tolerant: nulls and wrong JSON types never throw.
 */
public final class PlatformFormMapper {

    private static final Pattern NAME = Pattern.compile("[A-Za-z][A-Za-z0-9_-]{0,63}");
    private static final Map<String, String> TYPES = Map.ofEntries(
            Map.entry("texto", "text"), Map.entry("text", "text"), Map.entry("email", "email"), Map.entry("correo", "email"),
            Map.entry("telefono", "tel"), Map.entry("tel", "tel"), Map.entry("numero", "number"), Map.entry("entero", "number"),
            Map.entry("decimal", "number"), Map.entry("fecha", "date"), Map.entry("date", "date"),
            Map.entry("textoarea", "textarea"), Map.entry("textarea", "textarea"), Map.entry("area", "textarea"),
            Map.entry("checkbox", "checkbox"), Map.entry("check", "checkbox"),
            Map.entry("archivo", "file"), Map.entry("file", "file"), Map.entry("adjunto", "file"), Map.entry("documento", "file"));
    private static final int MAX_FIELDS = 200;

    private final ObjectMapper mapper;

    public PlatformFormMapper(ObjectMapper mapper) {
        this.mapper = mapper;
    }

    /**
     * Capture model of {@code resource}. Hidden fields are part of the form (flagged {@code hidden}, so the renderer keeps them out of sight
     * but they are posted with it), except those whose default is still an unresolved {@code ${...}} placeholder: posting such a field empty
     * would override the platform's own default (a blank uuid as the key). Never null.
     */
    public ObjectNode toBuilderModel(JsonNode resource) {
        return toBuilderModel(resource, false);
    }

    /**
     * Model of {@code resource}. With {@code forEditing} the builder gets the form as it is stored: every hidden field is included and every
     * field carries {@code isId} / {@code showInBasket}, so what the designer shows and saves back is the truth and not a default. Without it
     * (data capture) see {@link #toBuilderModel(JsonNode)}; those editing flags are not emitted.
     */
    public ObjectNode toBuilderModel(JsonNode resource, boolean forEditing) {
        ObjectNode out = mapper.createObjectNode();
        ObjectNode meta = out.putObject("meta");
        String title = text(resource, "title");
        meta.put("title", title.isEmpty() ? text(resource, "name") : title);
        meta.put("description", text(resource, "instruction"));
        meta.put("submit", "Guardar");
        meta.put("method", "post");
        meta.put("name", text(resource, "name"));
        meta.put("module", text(resource, "module"));
        meta.put("version", text(resource, "version"));
        meta.put("table", text(resource, "table"));
        ArrayNode fields = out.putArray("fields");
        JsonNode model = resource == null ? null : resource.get("model");
        if (model == null || !model.isArray()) {
            return out;
        }
        List<JsonNode> ordered = new ArrayList<>();
        model.forEach(ordered::add);
        ordered.sort((a, b) -> Integer.compare(a.path("order").asInt(0), b.path("order").asInt(0)));
        for (JsonNode f : ordered) {
            boolean hidden = f.path("hidden").asBoolean(false);
            if (fields.size() >= MAX_FIELDS || !f.isObject()) {
                continue;
            }
            if (hidden && !forEditing && text(f, "value").contains("${")) {
                continue;   // unresolved default: leave it to the platform, do not post an empty value over it
            }
            String name = text(f, "fieldName");
            if (name.isEmpty()) {
                name = text(f, "name");
            }
            // `codigo` is generated by the platform from the resource prefix; typing it would only cause key clashes
            if (!NAME.matcher(name).matches() || "codigo".equalsIgnoreCase(name)) {
                continue;
            }
            ObjectNode o = fields.addObject();
            o.put("name", name);
            String label = text(f, "label");
            o.put("label", label.isEmpty() ? name : label);
            // nobody can fill a hidden field in: when capturing, it must never block the submit
            o.put("required", f.path("required").asBoolean(false) && (forEditing || !hidden));
            if (f.path("readOnly").asBoolean(false)) {
                o.put("readOnly", true);
            }
            if (hidden) o.put("hidden", true);
            if (forEditing) {
                if (f.path("id").asBoolean(false)) o.put("isId", true);
                if (f.path("showInBasket").asBoolean(false)) o.put("showInBasket", true);
            }
            String type = TYPES.getOrDefault(text(f, "componentType").toLowerCase(Locale.ROOT), null);
            List<String> options = inlineValues(text(f, "origin"));
            if ("catalogo".equalsIgnoreCase(text(f, "componentType")) && !forEditing && !hidden) {
                // several rows of a table, each with a quantity: the capture page asks the platform for the rows (case/form/catalogo/items) and draws them
                o.put("type", "catalog");
                o.put("catalogOrigin", text(f, "origin"));
            } else if (options != null && !options.isEmpty()) {
                o.put("type", "select");
                ArrayNode opts = o.putArray("options");
                options.forEach(opts::add);
                o.put("placeholder", "");
            } else {
                if (type == null) {
                    type = byDbType(text(f, "dbFieldType"));
                }
                o.put("type", type);
                if ("number".equals(type) && !text(f, "dbFieldType").isEmpty()) {
                    o.put("step", "decimal".equalsIgnoreCase(text(f, "dbFieldType")) ? "0.01" : "1");
                }
            }
            String value = text(f, "value");
            if (!value.isEmpty() && !value.contains("${")) {
                o.put("value", value);
            }
            String suggestion = text(f, "suggestion");
            if (!suggestion.isEmpty()) {
                o.put("placeholder", suggestion);
            }
        }
        return out;
    }

    private static String byDbType(String dbType) {
        return switch (dbType.toLowerCase(Locale.ROOT)) {
            case "date" -> "date";
            case "int", "bigint", "decimal", "double" -> "number";
            case "boolean", "bit" -> "checkbox";
            default -> "text";
        };
    }

    /** Values of an inline list field: {"origin":"recurso","resource":"inlinevalues","fields":[{"name":"A,B,C"}]}. */
    private List<String> inlineValues(String origin) {
        if (origin.isEmpty() || !origin.contains("inlinevalues")) {
            return null;
        }
        try {
            JsonNode n = mapper.readTree(origin).path("fields").path(0).path("name");
            if (!n.isTextual()) {
                return null;
            }
            List<String> out = new ArrayList<>();
            for (String s : n.asText().split(",")) {
                String v = s.trim();
                if (!v.isEmpty() && v.length() <= 200 && out.size() < 100) {
                    out.add(v);
                }
            }
            return out;
        } catch (Exception e) {
            return null;
        }
    }

    private static String text(JsonNode n, String field) {
        if (n == null) {
            return "";
        }
        JsonNode v = n.get(field);
        return v == null || v.isNull() || v.isContainerNode() ? "" : v.asText("").trim();
    }
}
